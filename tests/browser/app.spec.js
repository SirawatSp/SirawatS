import { test, expect } from '@playwright/test';
import path from 'node:path';
import JSZip from 'jszip';
import fs from 'node:fs/promises';

test('real face detection, naming, solo filtering, persistence and ZIP export', async ({ page }) => {
  const errors = [];
  const externalRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    if (!request.url().startsWith('http://127.0.0.1:5173/') && !request.url().startsWith('blob:') && !request.url().startsWith('data:')) externalRequests.push(request.url());
  });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Your photo library' })).toBeVisible();
  await page.getByRole('button', { name: 'Create a trip', exact: true }).click();
  await page.getByLabel('Trip name').fill('Autumn adventure');
  await page.locator('#trip-form').getByRole('button', { name: 'Create trip', exact: false }).click();
  await expect(page.getByRole('heading', { name: 'Autumn adventure' })).toBeVisible();
  const sample = path.resolve('node_modules/@vladmandic/face-api/demo/sample1.jpg');
  await page.locator('#photo-input').setInputFiles(sample);
  await expect(page.locator('.photo-card')).toHaveCount(1, { timeout: 120_000 });
  await expect(page.locator('.progress-panel')).toBeHidden({ timeout: 120_000 });
  await expect(page.locator('.type-error')).toHaveCount(0);
  await page.locator('.photo-open').click();
  const faceCount = await page.locator('.face-tile').count();
  expect(faceCount).toBeGreaterThan(0);
  console.log(`Real detector found ${faceCount} face(s) in bundled sample1.jpg`);
  await page.locator('.face-tile').first().click();
  await page.getByLabel('New person’s name').fill('Alex');
  await page.getByRole('button', { name: 'Confirm face' }).click();
  await expect(page.locator('.face-tile').first()).toContainText('Alex');
  await expect(page.locator('.face-tile').first()).toContainText('Confirmed by you');
  await page.getByLabel('Total people in this photo').fill('2');
  await page.locator('#count-form').getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.locator('.filter-tabs').getByRole('button', { name: 'Solo shots' }).click();
  await expect(page.locator('.photo-card')).toHaveCount(0);
  await page.locator('.filter-tabs').getByRole('button', { name: 'Together' }).click();
  await expect(page.locator('.photo-card')).toHaveCount(1);
  await page.reload();
  await expect(page.locator('.photo-card')).toHaveCount(1);
  await expect(page.locator('.person-chip').filter({ hasText: 'Alex' })).toBeVisible();
  const crop = await page.evaluate(async () => {
    const { getLibrary } = await import('/src/storage.js');
    const { photos } = await getLibrary();
    return Array.from(new Uint8Array(await photos[0].faces[0].thumbnail.arrayBuffer()));
  });
  await page.locator('#photo-input').setInputFiles({name:'alex-portrait.jpg',mimeType:'image/jpeg',buffer:Buffer.from(crop)});
  await expect(page.locator('.photo-card')).toHaveCount(2, {timeout:120_000});
  await expect(page.locator('.progress-panel')).toBeHidden({timeout:120_000});
  await page.locator('.filter-tabs').getByRole('button', {name:'Solo shots'}).click();
  await expect(page.locator('.photo-card')).toHaveCount(1);
  await expect(page.locator('.photo-card')).toContainText('Alex');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', {name:'Export photos',exact:true}).click();
  const download = await downloadPromise;
  const zip = await JSZip.loadAsync(await fs.readFile(await download.path()));
  expect(zip.file('Alex/alex-portrait.jpg')).toBeTruthy();
  const manifest = JSON.parse(await zip.file('manifest.json').async('string'));
  expect(manifest.photos).toHaveLength(1);
  expect(JSON.stringify(manifest)).not.toContain('descriptor');
  await page.locator('#photo-input').setInputFiles({name:'alex-portrait.jpg',mimeType:'image/jpeg',buffer:Buffer.from(crop)});
  await expect(page.locator('.progress-panel')).toBeHidden({timeout:120_000});
  await page.locator('.filter-tabs').getByRole('button', {name:'All photos',exact:true}).click();
  await expect(page.locator('.photo-card')).toHaveCount(2);
  await page.screenshot({path:'/tmp/roam-library.png',fullPage:true});
  expect(errors).toEqual([]);
  expect(externalRequests).toEqual([]);
});

test('mobile layout, empty export, and safe cancellation', async ({ page }) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await expect(page.getByRole('button', {name:'Export photos',exact:true})).toBeDisabled();
  expect(await page.locator('body').evaluate(e=>e.scrollWidth)).toBeLessThanOrEqual(390);
  await page.getByRole('button',{name:'Toggle navigation'}).click();
  await page.getByRole('button',{name:'Library & storage'}).click();
  await page.getByRole('button',{name:'Clear library…'}).click();
  await page.getByRole('button',{name:'Keep library'}).click();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.getByRole('button',{name:'Close navigation'}).click();
  await page.screenshot({path:'/tmp/roam-mobile.png',fullPage:true});
});
